CREATE TABLE PRODUTOR (
    id_produtor     NUMBER(10)      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome            VARCHAR2(100)   NOT NULL,
    email           VARCHAR2(150)   NOT NULL,
    senha           VARCHAR2(255)   NOT NULL,
    municipio       VARCHAR2(80)    NOT NULL,
    regiao          VARCHAR2(60)    NOT NULL,
    data_cadastro   DATE            DEFAULT SYSDATE NOT NULL,
    CONSTRAINT uk_produtor_email UNIQUE (email)
);

CREATE TABLE AREA (
    id_area         NUMBER(10)      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_produtor     NUMBER(10)      NOT NULL,
    nome            VARCHAR2(100)   NOT NULL,
    tamanho_ha      NUMBER(8,2)     NOT NULL,
    latitude        NUMBER(10,7)    NOT NULL,
    longitude       NUMBER(10,7)    NOT NULL,
    data_cadastro   DATE            DEFAULT SYSDATE NOT NULL,
    CONSTRAINT fk_area_produtor FOREIGN KEY (id_produtor)
        REFERENCES PRODUTOR (id_produtor),
    CONSTRAINT ck_area_tamanho CHECK (tamanho_ha > 0),
    CONSTRAINT ck_area_latitude CHECK (latitude BETWEEN -90 AND 90),
    CONSTRAINT ck_area_longitude CHECK (longitude BETWEEN -180 AND 180)
);

CREATE TABLE CULTURA (
    id_cultura      NUMBER(10)      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_area         NUMBER(10)      NOT NULL,
    tipo            VARCHAR2(20)    NOT NULL,
    nome            VARCHAR2(80)    NOT NULL,
    data_plantio    DATE            NOT NULL,
    estagio         VARCHAR2(30)    NOT NULL,
    CONSTRAINT fk_cultura_area FOREIGN KEY (id_area)
        REFERENCES AREA (id_area),
    CONSTRAINT ck_cultura_tipo CHECK (tipo IN ('HORTALICA', 'FRUTA')),
    CONSTRAINT ck_cultura_estagio CHECK (estagio IN ('GERMINACAO','CRESCIMENTO','FLORACAO','COLHEITA'))
);

CREATE TABLE LEITURA_SOLO (
    id_leitura      NUMBER(10)      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_area         NUMBER(10)      NOT NULL,
    valor_umidade   NUMBER(5,2)     NOT NULL,
    data_hora       DATE            DEFAULT SYSDATE NOT NULL,
    origem          VARCHAR2(10)    NOT NULL,
    id_dispositivo  VARCHAR2(50),
    CONSTRAINT fk_leitura_area FOREIGN KEY (id_area)
        REFERENCES AREA (id_area),
    CONSTRAINT ck_leitura_umidade CHECK (valor_umidade BETWEEN 0 AND 100),
    CONSTRAINT ck_leitura_origem CHECK (origem IN ('SENSOR','MANUAL'))
);

CREATE TABLE ALERTA (
    id_alerta       NUMBER(10)      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cultura      NUMBER(10)      NOT NULL,
    tipo            VARCHAR2(20)    NOT NULL,
    severidade      VARCHAR2(15)    NOT NULL,
    mensagem        VARCHAR2(255)   NOT NULL,
    lido            CHAR(1)         DEFAULT 'N' NOT NULL,
    data_geracao    DATE            DEFAULT SYSDATE NOT NULL,
    CONSTRAINT fk_alerta_cultura FOREIGN KEY (id_cultura)
        REFERENCES CULTURA (id_cultura),
    CONSTRAINT ck_alerta_tipo CHECK (tipo IN ('CLIMA','IRRIGACAO','UMIDADE')),
    CONSTRAINT ck_alerta_severidade CHECK (severidade IN ('CRITICO','MODERADO','NORMAL')),
    CONSTRAINT ck_alerta_lido CHECK (lido IN ('S','N'))
);

CREATE TABLE PUBLICACAO (
    id_publicacao   NUMBER(10)      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_produtor     NUMBER(10)      NOT NULL,
    texto           VARCHAR2(500)   NOT NULL,
    cultura         VARCHAR2(80)    NOT NULL,
    regiao          VARCHAR2(60)    NOT NULL,
    data_publicacao DATE            DEFAULT SYSDATE NOT NULL,
    confirmacoes    NUMBER(6)       DEFAULT 0 NOT NULL,
    CONSTRAINT fk_publicacao_produtor FOREIGN KEY (id_produtor)
        REFERENCES PRODUTOR (id_produtor),
    CONSTRAINT ck_publicacao_confirmacoes CHECK (confirmacoes >= 0)
);

COMMIT;

