SET SERVEROUTPUT ON SIZE UNLIMITED;

DECLARE
    v_id_area        AREA.id_area%TYPE := 1;
    v_nome_area      AREA.nome%TYPE;
    v_umidade        LEITURA_SOLO.valor_umidade%TYPE;
    v_data_leitura   LEITURA_SOLO.data_hora%TYPE;
    v_classificacao  VARCHAR2(30);
    v_recomendacao   VARCHAR2(200);
BEGIN
    SELECT nome
      INTO v_nome_area
      FROM AREA
     WHERE id_area = v_id_area;

    SELECT valor_umidade, data_hora
      INTO v_umidade, v_data_leitura
      FROM LEITURA_SOLO
     WHERE id_area = v_id_area
       AND data_hora = (SELECT MAX(data_hora)
                          FROM LEITURA_SOLO
                         WHERE id_area = v_id_area);

    IF v_umidade < 20 THEN
        v_classificacao := 'CRITICO';
        v_recomendacao  := 'Irrigacao urgente. Risco alto de perda da safra.';
    ELSIF v_umidade < 35 THEN
        v_classificacao := 'MODERADO';
        v_recomendacao  := 'Irrigar nas proximas 24 horas.';
    ELSIF v_umidade <= 70 THEN
        v_classificacao := 'NORMAL';
        v_recomendacao  := 'Umidade adequada. Manter monitoramento.';
    ELSE
        v_classificacao := 'EXCESSO';
        v_recomendacao  := 'Solo encharcado. Suspender irrigacao.';
    END IF;

    DBMS_OUTPUT.PUT_LINE('=========================================');
    DBMS_OUTPUT.PUT_LINE('ANALISE DE UMIDADE DO SOLO');
    DBMS_OUTPUT.PUT_LINE('=========================================');
    DBMS_OUTPUT.PUT_LINE('Area.............: ' || v_nome_area);
    DBMS_OUTPUT.PUT_LINE('Umidade do solo..: ' || v_umidade || '%');
    DBMS_OUTPUT.PUT_LINE('Data da leitura..: ' || TO_CHAR(v_data_leitura,'DD/MM/YYYY HH24:MI'));
    DBMS_OUTPUT.PUT_LINE('Classificacao....: ' || v_classificacao);
    DBMS_OUTPUT.PUT_LINE('Recomendacao.....: ' || v_recomendacao);
    DBMS_OUTPUT.PUT_LINE('=========================================');

EXCEPTION
    WHEN NO_DATA_FOUND THEN
        DBMS_OUTPUT.PUT_LINE('ERRO: Nenhuma leitura encontrada para a area ' || v_id_area);
    WHEN OTHERS THEN
        DBMS_OUTPUT.PUT_LINE('ERRO INESPERADO: ' || SQLERRM);
END;
/

DECLARE
    v_umidade       LEITURA_SOLO.valor_umidade%TYPE;
    v_classificacao VARCHAR2(30);
    v_total_critico NUMBER := 0;
    v_total_moderado NUMBER := 0;
    v_total_normal  NUMBER := 0;
BEGIN
    DBMS_OUTPUT.PUT_LINE('=========================================');
    DBMS_OUTPUT.PUT_LINE('CLASSIFICACAO DE TODAS AS AREAS');
    DBMS_OUTPUT.PUT_LINE('=========================================');

    FOR r_area IN (SELECT a.id_area, a.nome
                     FROM AREA a
                    ORDER BY a.id_area)
    LOOP
        BEGIN
            SELECT valor_umidade
              INTO v_umidade
              FROM LEITURA_SOLO
             WHERE id_area = r_area.id_area
               AND data_hora = (SELECT MAX(data_hora)
                                  FROM LEITURA_SOLO
                                 WHERE id_area = r_area.id_area);

            IF v_umidade < 20 THEN
                v_classificacao := 'CRITICO';
                v_total_critico := v_total_critico + 1;
            ELSIF v_umidade < 35 THEN
                v_classificacao := 'MODERADO';
                v_total_moderado := v_total_moderado + 1;
            ELSE
                v_classificacao := 'NORMAL';
                v_total_normal := v_total_normal + 1;
            END IF;

            DBMS_OUTPUT.PUT_LINE('Area ' || r_area.id_area || ' - ' ||
                                 RPAD(r_area.nome, 25) || ' | ' ||
                                 LPAD(v_umidade, 6) || '% | ' ||
                                 v_classificacao);
        EXCEPTION
            WHEN NO_DATA_FOUND THEN
                DBMS_OUTPUT.PUT_LINE('Area ' || r_area.id_area || ' - ' ||
                                     RPAD(r_area.nome, 25) || ' | SEM LEITURA');
        END;
    END LOOP;

    DBMS_OUTPUT.PUT_LINE('-----------------------------------------');
    DBMS_OUTPUT.PUT_LINE('TOTAL CRITICO..: ' || v_total_critico);
    DBMS_OUTPUT.PUT_LINE('TOTAL MODERADO.: ' || v_total_moderado);
    DBMS_OUTPUT.PUT_LINE('TOTAL NORMAL...: ' || v_total_normal);
    DBMS_OUTPUT.PUT_LINE('=========================================');
END;
/

DECLARE
    v_ciclo         NUMBER := 1;
    v_areas_criticas NUMBER;
BEGIN
    DBMS_OUTPUT.PUT_LINE('=========================================');
    DBMS_OUTPUT.PUT_LINE('SIMULACAO DE CICLOS DE IRRIGACAO');
    DBMS_OUTPUT.PUT_LINE('=========================================');

    SELECT COUNT(*)
      INTO v_areas_criticas
      FROM LEITURA_SOLO l
     WHERE l.valor_umidade < 20
       AND l.data_hora = (SELECT MAX(l2.data_hora)
                            FROM LEITURA_SOLO l2
                           WHERE l2.id_area = l.id_area);

    WHILE v_ciclo <= 5 LOOP
        DBMS_OUTPUT.PUT_LINE('Ciclo ' || v_ciclo ||
                             ' - Areas criticas no inicio: ' || v_areas_criticas);
        v_areas_criticas := v_areas_criticas - 1;
        IF v_areas_criticas < 0 THEN
            v_areas_criticas := 0;
        END IF;
        v_ciclo := v_ciclo + 1;
    END LOOP;

    DBMS_OUTPUT.PUT_LINE('-----------------------------------------');
    DBMS_OUTPUT.PUT_LINE('Fim da simulacao. Areas criticas restantes: ' || v_areas_criticas);
    DBMS_OUTPUT.PUT_LINE('=========================================');
END;
/

-- ============================================================
-- PARTE 4 - CURSOR EXPLICITO E PROCEDIMENTOS ARMAZENADOS
-- ============================================================

DECLARE
    CURSOR c_areas_criticas IS
        SELECT p.nome            AS produtor,
               a.nome            AS area,
               c.nome            AS cultura,
               l.valor_umidade   AS umidade,
               l.data_hora       AS data_leitura
          FROM PRODUTOR p
          JOIN AREA a         ON a.id_produtor = p.id_produtor
          JOIN CULTURA c      ON c.id_area = a.id_area
          JOIN LEITURA_SOLO l ON l.id_area = a.id_area
         WHERE l.valor_umidade < 20
           AND l.data_hora = (SELECT MAX(l2.data_hora)
                                FROM LEITURA_SOLO l2
                               WHERE l2.id_area = a.id_area)
         ORDER BY l.valor_umidade;

    v_registro   c_areas_criticas%ROWTYPE;
    v_contador   NUMBER := 0;
BEGIN
    DBMS_OUTPUT.PUT_LINE('=========================================');
    DBMS_OUTPUT.PUT_LINE('AREAS COM UMIDADE CRITICA (abaixo de 20%)');
    DBMS_OUTPUT.PUT_LINE('=========================================');

    OPEN c_areas_criticas;
    LOOP
        FETCH c_areas_criticas INTO v_registro;
        EXIT WHEN c_areas_criticas%NOTFOUND;

        v_contador := v_contador + 1;

        DBMS_OUTPUT.PUT_LINE('Registro ' || v_contador);
        DBMS_OUTPUT.PUT_LINE('  Produtor.....: ' || v_registro.produtor);
        DBMS_OUTPUT.PUT_LINE('  Area.........: ' || v_registro.area);
        DBMS_OUTPUT.PUT_LINE('  Cultura......: ' || v_registro.cultura);
        DBMS_OUTPUT.PUT_LINE('  Umidade......: ' || v_registro.umidade || '%');
        DBMS_OUTPUT.PUT_LINE('  Leitura......: ' || TO_CHAR(v_registro.data_leitura,'DD/MM/YYYY HH24:MI'));
        DBMS_OUTPUT.PUT_LINE('  Acao.........: Irrigacao urgente necessaria');
        DBMS_OUTPUT.PUT_LINE('-----------------------------------------');
    END LOOP;
    CLOSE c_areas_criticas;

    DBMS_OUTPUT.PUT_LINE('Total de areas criticas: ' || v_contador);
    DBMS_OUTPUT.PUT_LINE('=========================================');
END;
/

CREATE OR REPLACE PROCEDURE sp_registrar_leitura (
    p_id_area       IN NUMBER,
    p_umidade       IN NUMBER,
    p_origem        IN VARCHAR2,
    p_id_dispositivo IN VARCHAR2 DEFAULT NULL
) IS
    v_id_cultura    CULTURA.id_cultura%TYPE;
    v_nome_cultura  CULTURA.nome%TYPE;
    v_severidade    ALERTA.severidade%TYPE;
    v_mensagem      ALERTA.mensagem%TYPE;
BEGIN
    BEGIN
        SELECT c.id_cultura, c.nome
          INTO v_id_cultura, v_nome_cultura
          FROM CULTURA c
         WHERE c.id_area = p_id_area
           AND ROWNUM = 1;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            RAISE_APPLICATION_ERROR(-20001,
                'Area ' || p_id_area || ' nao possui cultura cadastrada.');
    END;

    INSERT INTO LEITURA_SOLO (id_area, valor_umidade, origem, id_dispositivo)
    VALUES (p_id_area, p_umidade, p_origem, p_id_dispositivo);

    IF p_umidade < 20 THEN
        v_severidade := 'CRITICO';
        v_mensagem   := 'Umidade do solo em ' || p_umidade ||
                        '% - irrigacao urgente para ' || v_nome_cultura;
    ELSIF p_umidade < 35 THEN
        v_severidade := 'MODERADO';
        v_mensagem   := 'Umidade do solo em ' || p_umidade ||
                        '% - irrigar nas proximas 24h para ' || v_nome_cultura;
    ELSE
        v_severidade := 'NORMAL';
        v_mensagem   := 'Umidade do solo em ' || p_umidade ||
                        '% - dentro da faixa ideal para ' || v_nome_cultura;
    END IF;

    INSERT INTO ALERTA (id_cultura, tipo, severidade, mensagem)
    VALUES (v_id_cultura, 'UMIDADE', v_severidade, v_mensagem);

    COMMIT;

    DBMS_OUTPUT.PUT_LINE('Leitura registrada na area ' || p_id_area ||
                         ' (' || p_umidade || '%) - Alerta ' || v_severidade || ' gerado.');

EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK;
        DBMS_OUTPUT.PUT_LINE('ERRO ao registrar leitura: ' || SQLERRM);
        RAISE;
END;
/

CREATE OR REPLACE PROCEDURE sp_relatorio_produtor (
    p_id_produtor IN NUMBER
) IS
    v_nome_produtor PRODUTOR.nome%TYPE;
    v_municipio     PRODUTOR.municipio%TYPE;
    v_qtd_areas     NUMBER;
    v_qtd_alertas   NUMBER;
    v_qtd_criticos  NUMBER;
BEGIN
    SELECT nome, municipio
      INTO v_nome_produtor, v_municipio
      FROM PRODUTOR
     WHERE id_produtor = p_id_produtor;

    SELECT COUNT(*)
      INTO v_qtd_areas
      FROM AREA
     WHERE id_produtor = p_id_produtor;

    SELECT COUNT(*)
      INTO v_qtd_alertas
      FROM ALERTA al
      JOIN CULTURA c ON c.id_cultura = al.id_cultura
      JOIN AREA a    ON a.id_area = c.id_area
     WHERE a.id_produtor = p_id_produtor;

    SELECT COUNT(*)
      INTO v_qtd_criticos
      FROM ALERTA al
      JOIN CULTURA c ON c.id_cultura = al.id_cultura
      JOIN AREA a    ON a.id_area = c.id_area
     WHERE a.id_produtor = p_id_produtor
       AND al.severidade = 'CRITICO';

    DBMS_OUTPUT.PUT_LINE('=========================================');
    DBMS_OUTPUT.PUT_LINE('RELATORIO DO PRODUTOR');
    DBMS_OUTPUT.PUT_LINE('=========================================');
    DBMS_OUTPUT.PUT_LINE('Produtor.....: ' || v_nome_produtor);
    DBMS_OUTPUT.PUT_LINE('Municipio....: ' || v_municipio);
    DBMS_OUTPUT.PUT_LINE('Areas........: ' || v_qtd_areas);
    DBMS_OUTPUT.PUT_LINE('Total alertas: ' || v_qtd_alertas);
    DBMS_OUTPUT.PUT_LINE('Criticos.....: ' || v_qtd_criticos);
    DBMS_OUTPUT.PUT_LINE('-----------------------------------------');

    FOR r_area IN (SELECT a.nome AS area,
                          c.nome AS cultura,
                          c.estagio,
                          (SELECT MAX(l.valor_umidade)
                             FROM LEITURA_SOLO l
                            WHERE l.id_area = a.id_area) AS ultima_umidade
                     FROM AREA a
                     LEFT JOIN CULTURA c ON c.id_area = a.id_area
                    WHERE a.id_produtor = p_id_produtor
                    ORDER BY a.nome)
    LOOP
        DBMS_OUTPUT.PUT_LINE('Area: ' || RPAD(r_area.area, 25) ||
                             ' | Cultura: ' || RPAD(NVL(r_area.cultura,'-'), 20) ||
                             ' | Estagio: ' || RPAD(NVL(r_area.estagio,'-'), 12) ||
                             ' | Umidade: ' || NVL(TO_CHAR(r_area.ultima_umidade),'--'));
    END LOOP;

    DBMS_OUTPUT.PUT_LINE('=========================================');

EXCEPTION
    WHEN NO_DATA_FOUND THEN
        DBMS_OUTPUT.PUT_LINE('ERRO: Produtor ' || p_id_produtor || ' nao encontrado.');
    WHEN OTHERS THEN
        DBMS_OUTPUT.PUT_LINE('ERRO no relatorio: ' || SQLERRM);
END;
/

